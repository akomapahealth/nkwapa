/** The band a value falls in: 0 below the first edge, up to edges.length at or above the last. */
function bandIndex(value: number, edges: readonly number[]): number {
  return edges.filter((edge) => value >= edge).length;
}

export interface ChartCellQuery {
  table: ChartTable;
  sex: 'MALE' | 'FEMALE';
  smoker: boolean;
  ageYears: number;
  systolic: number;
  /** BMI on the non-laboratory chart, total cholesterol in mmol/L on the laboratory chart. */
  columnValue: number;
  columnEdges: readonly number[];
}

/** The printed percentage for one person, or null when their age is outside 40 to 74. */
export function chartCell(query: ChartCellQuery): number | null {
  const age = Math.floor(query.ageYears);
  if (!Number.isFinite(age) || age < CHART_MIN_AGE || age > CHART_MAX_AGE) return null;
  const ageBand = CHART_AGE_BANDS[Math.floor((age - CHART_MIN_AGE) / 5)];
  // Rows are printed highest systolic first.
  const row = CHART_SYSTOLIC_EDGES.length - bandIndex(query.systolic, CHART_SYSTOLIC_EDGES);
  const group = (query.sex === 'MALE' ? 0 : 2) + (query.smoker ? 1 : 0);
  const column = group * 5 + bandIndex(query.columnValue, query.columnEdges);
  return query.table[ageBand][row][column];
}
