/**
 * WHO cardiovascular disease risk charts, Western Sub-Saharan Africa (Ghana's region).
 *
 * Source: World Health Organization. HEARTS technical package for cardiovascular disease
 * management in primary health care: risk-based CVD management. Geneva: WHO; 2020.
 * ISBN 978-92-4-000136-7. https://iris.who.int/handle/10665/333221
 *   - Annex 2, laboratory-based chart: printed page 35 (PDF page 37).
 *   - Annex 3, non-laboratory-based chart: printed page 56 (PDF page 58).
 * Retrieved 2026-11-16 (PDF SHA-256 1f836448bc5f0455b717d9c1d6fc4cb057a286b8303fa940bf14c356785e2510).
 * These are the 2019 WHO charts (Kaptoge et al., Lancet Glob Health 2019), not the 2007 WHO/ISH
 * charts, which use different regions and bands.
 *
 * How this was made: the numbers were read from the PDF's own text layer, not retyped, and laid
 * out exactly as printed so a reviewer can hold this file against the page. Every cell was then
 * checked to rise (never fall) with age, systolic BP, smoking, BMI, cholesterol and diabetes,
 * which a shifted row or column would break, and the spec checks a table of cells by eye.
 *
 * Do not edit a number here without the page open. A wrong cell is a clinical error.
 *
 * Layout, as printed:
 * - One block per age band, oldest first.
 * - Five rows per block, systolic BP highest first: >=180, 160-179, 140-159, 120-139, <120.
 * - Twenty columns per row: men non-smoker, men smoker, women non-smoker, women smoker, five
 *   columns each, lowest band first. The five columns are BMI bands on the non-laboratory chart
 *   and total cholesterol bands on the laboratory chart.
 * - Each cell is the 10-year risk of a fatal or non-fatal heart attack or stroke, in percent.
 */

/**
 * The chart's own axes. They are part of the published chart, not settings: moving an edge
 * without re-reading the table would pair a band with the wrong numbers.
 *
 * The printed labels are whole numbers ("20-24", "4-4.9"); each band runs up to the next band's
 * lower edge, so a BMI of 24.6 is in 20-24 and a cholesterol of 4.95 is in 4-4.9.
 */
