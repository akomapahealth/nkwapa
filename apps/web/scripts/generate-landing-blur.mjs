// Writes lib/landing-blur.ts: a tiny blurred WebP for each landing photograph, used as the
// next/image placeholder while the real one loads (#280). Run from apps/web after replacing a photo:
//   node scripts/generate-landing-blur.mjs
import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dir = path.join(root, 'public/images');
const photos = (await readdir(dir)).filter((name) => /^Akomapa-\d+\.jpg$/.test(name)).sort();

const lines = [];
for (const name of photos) {
  // 16px on the long edge: enough for the photograph's colour masses, a few hundred bytes each.
  const buffer = await sharp(path.join(dir, name))
    .rotate()
    .resize(16, 16, { fit: 'inside' })
    .webp({ quality: 50 })
    .toBuffer();
  lines.push(`  '/images/${name}': 'data:image/webp;base64,${buffer.toString('base64')}',`);
}

await writeFile(
  path.join(root, 'lib/landing-blur.ts'),
  `// Generated by scripts/generate-landing-blur.mjs. Do not edit by hand.\n` +
    `export const LANDING_BLUR: Record<string, string> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`Wrote ${photos.length} placeholders.`);
