export function hasPermission(userRoles: { role: UserRole }[], required: string): boolean {
  for (const { role } of userRoles) {
    const perms = ROLE_PERMISSIONS[role];
    if (perms.includes('*') || perms.includes(required)) {
      return true;
    }
  }
  return false;
}

export function computeEffectivePermissions(roles: UserRole[]): string[] {
  const perms = new Set<string>();
  for (const role of roles) {
    const rolePerms = ROLE_PERMISSIONS[role];
    if (rolePerms.includes('*')) return ['*'];
    for (const p of rolePerms) perms.add(p);
  }
  return [...perms];
}
